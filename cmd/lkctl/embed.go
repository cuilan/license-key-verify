package main

import (
	"encoding/base64"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/cuilan/license-key-verify/v2/pkg/crypto"
)

// xorKey 公钥混淆用的异或密钥
const xorKey = 0x5A

func handleEmbed() {
	fs := flag.NewFlagSet("embed", flag.ExitOnError)
	publicKey := fs.String("public-key", "", "Public key PEM file (required)")
	out := fs.String("out", "", "Output Go source file (required)")
	pkgName := fs.String("package", "", "Package name of the generated file (default: auto-detect from the target directory)")
	fs.Parse(os.Args[2:])

	if *publicKey == "" || *out == "" {
		fmt.Println("Usage: lkctl embed --public-key <pem> --out <file> [--package <name>]")
		os.Exit(2)
	}

	// 未显式指定包名时，从输出目录已有的 Go 文件检测包名：
	// 放进 pkg/license/（同包）与放进应用子包（如 licensekey/）都能直接编译。
	explicitPkg := false
	fs.Visit(func(f *flag.Flag) {
		if f.Name == "package" {
			explicitPkg = true
		}
	})
	if !explicitPkg {
		dir := filepath.Dir(*out)
		if detected := detectPackage(dir, filepath.Base(*out)); detected != "" {
			*pkgName = detected
		} else if base := filepath.Base(dir); isValidPkgName(base) {
			// 空目录（新建子包场景）：沿用 Go 惯例，包名 = 目录名
			*pkgName = base
			fmt.Printf("Note: no Go files found next to the output, using directory name %q as package name\n", base)
		} else {
			*pkgName = "license"
			fmt.Println("Note: falling back to package \"license\"")
		}
	} else if *pkgName == "" {
		fatal("--package cannot be empty")
	}

	pemData, err := os.ReadFile(*publicKey)
	if err != nil {
		fatal("Failed to read public key: %v", err)
	}
	if _, err := crypto.LoadPublicKeyFromPEM(pemData); err != nil {
		fatal("Invalid public key: %v", err)
	}

	// XOR 混淆后 Base64，避免 strings 直接搜出 PEM 内容
	obfuscated := make([]byte, len(pemData))
	for i, b := range pemData {
		obfuscated[i] = b ^ xorKey
	}
	encoded := base64.StdEncoding.EncodeToString(obfuscated)

	// 同包场景（fork 仓库替换 pkg/license/key.go）直接调包内函数；
	// 其他包场景 import 本模块的 license 包注册。
	const licensePkgPath = "github.com/cuilan/license-key-verify/v2/pkg/license"
	var initBlock string
	if *pkgName == "license" {
		initBlock = `
func init() {
	// 无效的内置公钥不在此处 panic，首次验证时通过明确错误暴露
	_ = UsePublicKeyPEM(embeddedPublicKey)
}`
	} else {
		initBlock = fmt.Sprintf(`
import "%s"

func init() {
	// 无效的内置公钥不在此处 panic，首次验证时通过明确错误暴露
	_ = license.UsePublicKeyPEM(embeddedPublicKey)
}`, licensePkgPath)
	}

	code := fmt.Sprintf(`// Code generated by lkctl embed. DO NOT EDIT.

package %s

import "encoding/base64"
%s

// embeddedPublicKey 经 XOR 混淆后内嵌的公钥（PEM），运行时还原。
// 目的是防止 strings 等工具直接搜出公钥内容，并非加密保护。
var embeddedPublicKey = decodeXOR("%s", 0x%02X)

// decodeXOR 还原被异或混淆的公钥数据。
func decodeXOR(data string, key byte) []byte {
	raw, err := base64.StdEncoding.DecodeString(data)
	if err != nil {
		return nil
	}
	out := make([]byte, len(raw))
	for i := range raw {
		out[i] = raw[i] ^ key
	}
	return out
}
`, *pkgName, initBlock, encoded, xorKey)

	if err := os.MkdirAll(filepath.Dir(*out), 0755); err != nil {
		fatal("Failed to create output directory: %v", err)
	}
	if err := os.WriteFile(*out, []byte(code), 0644); err != nil {
		fatal("Failed to write output file: %v", err)
	}
	fmt.Printf("Embedded public key written to %s (package %s)\n", *out, *pkgName)
	if *pkgName == "license" {
		fmt.Println("NOTE: place this file inside pkg/license/ and rebuild.")
	} else {
		fmt.Printf("NOTE: this file imports %s; make sure your module requires it.\n", licensePkgPath)
	}
}

// detectPackage 返回 dir 下第一个 Go 文件（排除 exclude）声明的包名，找不到返回空。
func detectPackage(dir, exclude string) string {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return ""
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || e.Name() == exclude {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			continue
		}
		for _, line := range strings.Split(string(data), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "package ") {
				return strings.TrimSpace(strings.TrimPrefix(line, "package "))
			}
		}
	}
	return ""
}

// isValidPkgName 判断是否为合法的 Go 包名（小写字母开头，字母/数字/下划线）。
func isValidPkgName(name string) bool {
	if name == "" || len(name) > 64 {
		return false
	}
	for i, r := range name {
		switch {
		case r >= 'a' && r <= 'z':
		case r >= '0' && r <= '9' && i > 0:
		case r == '_':
		default:
			return false
		}
	}
	return true
}
