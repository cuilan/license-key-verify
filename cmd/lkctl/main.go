package main

import (
	"fmt"
	"os"

	"github.com/cuilan/license-key-verify/pkg/license"
)

var (
	Version   = "dev" // will be set by -ldflags during build
	BuildTime = "unknown"
	GitCommit = "unknown"
)

const Usage = `
  lkctl - License Key Control Tool (vendor side)

  Usage:
    lkctl keygen --out keys/                 Generate an RSA key pair
    lkctl embed --public-key <pem> --out <file> [--package <name>]
                                             Embed a public key as a Go source file
    lkctl fingerprint                        Print this machine's fingerprint
    lkctl sign [options] --out license.lic   Sign a license
      --private-key <file>     Private key (required)
      --fingerprint <fp>       Target machine fingerprint (required)
      --duration <days>        Validity period (default: 365)
      --customer <name>        Customer name
      --product <name>         Product name
      --features <a,b,c>       Comma-separated feature list
      --license-id <id>        Custom license ID (auto-generated by default)
    lkctl verify <license-file> [--public-key <pem>] [--json] [--quiet]
                                             Verify a license
    lkctl info <license-file> [--public-key <pem>]    Show license content
    lkctl --version                          Show version
    lkctl --help                             Show this help message
`

func main() {
	if len(os.Args) < 2 {
		fmt.Print(Usage)
		os.Exit(1)
	}

	switch os.Args[1] {
	case "keygen":
		handleKeygen()
	case "embed":
		handleEmbed()
	case "fingerprint":
		license.PrintFingerprint()
	case "sign":
		handleSign()
	case "verify":
		handleVerify()
	case "info":
		handleInfo()
	case "--version", "version":
		fmt.Printf("lkctl version %s (built %s, commit %s)\n", Version, BuildTime, GitCommit)
	case "--help", "-h", "help":
		fmt.Print(Usage)
	default:
		fmt.Printf("Unknown command: %s\n", command())
		fmt.Print(Usage)
		os.Exit(1)
	}
}

func command() string {
	if len(os.Args) > 1 {
		return os.Args[1]
	}
	return ""
}

func fatal(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
