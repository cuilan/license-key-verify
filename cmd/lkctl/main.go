package main

import (
	"fmt"
	"os"

	"github.com/cuilan/license-key-verify/v2/pkg/license"
)

var (
	Version   = "dev" // will be set by -ldflags during build
	BuildTime = "unknown"
	GitCommit = "unknown"
)

const Usage = `
  lkctl - License Key Control Tool (vendor side)
  https://github.com/cuilan/license-key-verify/

  Usage:
    lkctl keygen                Generate an RSA key pair
        --out keys/             Output directory for the key pair
    lkctl embed                 Embed a public key as a Go source file
        --public-key <pem>      Public key PEM file (required)
        --out <file>            Output path of the generated Go source file
        --package <name>        Package name for the generated file (default: license)
    lkctl fingerprint           Print this machine's fingerprint
    lkctl sign                  Sign a license
        --out license.lic       Output license file path (required)
        --private-key <file>    Private key PEM file (required)
        --fingerprint <fp>      Target machine fingerprint (required)
        --duration <days>       Validity period in days (default: 365)
        --customer <name>       Customer name
        --product <name>        Product name
        --features <a,b,c>      Comma-separated feature list
        --license-id <id>       Custom license ID (auto-generated by default)
    lkctl verify <license-file> Verify a license
        --public-key <pem>      Public key PEM file (required unless the key is embedded)
        --json                  Output the result as JSON
        --quiet                 Suppress output, exit code only
    lkctl info <license-file>   Show license content
        --public-key <pem>      Public key PEM file (required unless the key is embedded)
    lkctl version               Show version
    lkctl help                  Show this help message
`

func main() {
	if len(os.Args) < 2 {
		fmt.Print(Usage)
		os.Exit(1)
	}

	switch os.Args[1] {
	case "keygen":
		handleKeygen()
	case "embed":
		handleEmbed()
	case "fingerprint":
		license.PrintFingerprint()
	case "sign":
		handleSign()
	case "verify":
		handleVerify()
	case "info":
		handleInfo()
	case "version":
		fmt.Printf("lkctl version %s (built %s, commit %s)\n", Version, BuildTime, GitCommit)
	case "help":
		fmt.Print(Usage)
	default:
		fmt.Printf("Unknown command: %s\n", command())
		fmt.Print(Usage)
		os.Exit(1)
	}
}

func command() string {
	if len(os.Args) > 1 {
		return os.Args[1]
	}
	return ""
}

func fatal(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
